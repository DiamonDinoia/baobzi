# deps/build.jl — locate libbaobzi_c and bake its path into deps/deps.jl.
#
# Run automatically by `Pkg.build("Baobzi")`. Resolution order:
#   1. the LIBBAOBZI_C environment variable (explicit path);
#   2. a sibling CMake `build*/libbaobzi_c.<ext>` found by walking up from
#      this package directory toward the repo root.
#
# If nothing is found we still write a deps.jl (with an empty path) so the
# runtime resolver in src/Baobzi.jl falls through to its own search; a build
# failure here must not block precompilation.

using Libdl

function find_in_build_tree(start::AbstractString)
    libname = "libbaobzi_c." * Libdl.dlext
    dir = abspath(start)
    while true
        for bd in sort(filter(isdir, readdir(dir; join = true)))
            if startswith(basename(bd), "build")
                cand = joinpath(bd, libname)
                isfile(cand) && return cand
            end
        end
        parent = dirname(dir)
        parent == dir && return nothing
        dir = parent
    end
end

function locate()
    env = get(ENV, "LIBBAOBZI_C", "")
    !isempty(env) && isfile(env) && return env
    walked = find_in_build_tree(@__DIR__)
    walked === nothing ? "" : walked
end

path = locate()

open(joinpath(@__DIR__, "deps.jl"), "w") do io
    println(io, "# Auto-generated by deps/build.jl — do not edit.")
    println(io, "# The final expression is the resolved libbaobzi_c path,")
    println(io, "# so `include(\"deps.jl\")` returns it.")
    println(io, repr(path))
end

if isempty(path)
    @warn "Baobzi build: libbaobzi_c not found; set LIBBAOBZI_C or build the project."
else
    @info "Baobzi build: using libbaobzi_c at $path"
end
